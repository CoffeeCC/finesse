// Requests Short, take A: real request on the Request page (search -> Request -> waiting in Requested).
import { stage, login, recorder, director, sleep, APP, VW } from './common.mjs'
const OUT = `${process.env.SHORTS_OUT || 'shorts-out'}/take-req-a`
const { browser, page } = await stage()
const d = director(page)
await login(page)
await page.goto(`${APP}/request`); await page.locator('h1', { hasText: 'Request' }).waitFor()
await sleep(5000)
const r = recorder(page, OUT)
await r.start()
await sleep(2200)
const inp = page.locator('input[placeholder="Search for a movie…"]')
r.mark('clickSearch'); await d.click(inp, { ms: 700, after: 400 })
r.mark('type'); await d.type('the iron giant', 85)
r.mark('typed')
await page.getByRole('button', { name: 'Request', exact: true }).first().waitFor()
await sleep(2200)
const btn = page.getByRole('button', { name: 'Request', exact: true }).first()
r.mark('hoverRequest'); await d.hover(btn, 800); await sleep(700)
r.mark('clickRequest'); await d.click(btn, { ms: 200, after: 500 })
await d.move(520, 205, 600); await sleep(2400)
r.mark('toast')
await sleep(1200)
const req = page.locator('h2', { hasText: /Requested|Waiting/ }).first()
const rb = await req.boundingBox().catch(() => null)
console.log('requested heading', rb, await page.locator('h2').allInnerTexts())
r.mark('scrollRequested')
await sleep(3500)
await r.stop()
await browser.close()
