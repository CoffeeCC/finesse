// short-04 v2: Home with real posters, then Customize Home (add a genre, move it up, hide a row, Done).
// Run from tools/tour/shorts: TOUR_SLOWMO=6 node cap-home.mjs
import { stage, login, recorder, director, sleep, VW } from './common.mjs'
const OUT = process.env.TAKE || `${process.env.SHORTS_OUT || 'shorts-out'}/take-home`
const { browser, page } = await stage()
const d = director(page)
await login(page)
await sleep(4000)
const r = recorder(page, OUT)
await r.start()
await sleep(2600)
r.mark('scroll1'); await d.scroll(520, 1500); await sleep(1600)
r.mark('scroll2'); await d.scroll(560, 1500); await sleep(1600)
r.mark('scroll3'); await d.scroll(560, 1500); await sleep(1600)
const cust = page.getByRole('button', { name: 'Customize Home' })
r.mark('toCustomize')
const b = await cust.boundingBox()
await d.scroll(Math.max(0, b.y - 600), 1400); await sleep(900)
r.mark('clickCustomize'); await d.click(cust, { ms: 800, after: 1300 })
const firstRow = page.getByRole('button', { name: 'Move up' }).first()
await page.evaluate(() => window.scrollTo({ top: 0 })); await sleep(300)
const fr = await firstRow.boundingBox()
r.mark('custList'); await d.scroll(Math.max(0, fr.y - 200), 900); await sleep(1300)
const chip = page.getByRole('button', { name: '+ Horror' })
r.mark('addGenre'); await d.click(chip, { ms: 800, after: 1300 })
const rowCtl = (title, name) => page.locator('div.rounded-xl', { hasText: title }).filter({ has: page.getByRole('button', { name: 'Move up' }) }).last().getByRole('button', { name })
r.mark('moveUp1'); await d.click(rowCtl('Horror', 'Move up'), { ms: 700, after: 700 })
r.mark('moveUp2'); await d.click(rowCtl('Horror', 'Move up'), { ms: 300, after: 700 })
r.mark('moveUp3'); await d.click(rowCtl('Horror', 'Move up'), { ms: 300, after: 900 })
const hide = rowCtl('Because you watched', /^Hide$/)
await hide.scrollIntoViewIfNeeded().catch(() => {})
r.mark('hide'); await d.click(hide, { ms: 800, after: 1300 })
const done = page.getByRole('button', { name: 'Done' })
r.mark('done'); await d.click(done, { ms: 800, after: 1500 })
// show the new Horror row on Home
const h = page.locator('h2', { hasText: 'Horror' }).first()
const hb = await h.boundingBox().catch(() => null)
r.mark('showHorror')
if (hb) { await d.scroll(hb.y - 120, 1300) }
await page.mouse.move(VW - 10, 200)
await sleep(3500)
await r.stop()
try {
  await page.evaluate(() => window.scrollTo({ top: 99999 })); await sleep(800)
  await page.getByRole('button', { name: 'Customize Home' }).click(); await sleep(1000)
  await page.getByRole('button', { name: 'Reset' }).click(); await sleep(1000)
  await page.getByRole('button', { name: 'Done' }).click(); await sleep(2000)
  console.log('layout reset')
} catch (e) { console.log('reset failed', e.message) }
await browser.close()
