# ---------- the terminal ----------
# Colour on a real terminal unless NO_COLOR/--plain. Nessa only where 256 colours or more work
# (SSH rarely passes COLORTERM along, so xterm-256color is the usual case). The Linux console
# gets plain symbols: its font has no ✔.
ART=0; COLS=80
if [ -t 1 ] && [ "$PLAIN" = 0 ] && [ -z "${NO_COLOR:-}" ] && [ "${TERM:-dumb}" != dumb ]; then
  ANIM=1
  case "${COLORTERM:-}" in truecolor|24bit) ART=tc ;; esac
  if [ "$ART" = 0 ]; then case "${TERM:-}" in *256color*|*-direct|xterm-kitty|alacritty|wezterm|foot*|contour) ART=256 ;; esac; fi
  if [ "$ART" = tc ]; then
    ACC=$'\e[38;2;167;139;250m'; HAIR=$'\e[38;2;92;180;255m'; PINK=$'\e[38;2;244;114;182m'
  elif [ "$ART" = 256 ]; then
    ACC=$'\e[38;5;141m'; HAIR=$'\e[38;5;75m'; PINK=$'\e[38;5;212m'
  else
    ACC=$'\e[35m'; HAIR=$'\e[36m'; PINK=$'\e[35m'
  fi
  B=$'\e[1m'; D=$'\e[2m'; G=$'\e[32m'; Y=$'\e[33m'; R=$'\e[31m'; N=$'\e[0m'
  if [ "${TERM:-}" = linux ]; then
    ART=0; I_OK="*"
  else
    I_OK="✔"; I_ERR="✖"; RULE="─"
  fi
  c=$(stty size </dev/tty 2>/dev/null | awk '{print $2}' || true)
  case "$c" in ''|*[!0-9]*) ;; *) COLS=$c ;; esac
fi
if [ "$I_OK" = "✔" ]; then SPIN=('⠋' '⠙' '⠹' '⠸' '⠼' '⠴' '⠦' '⠧' '⠇' '⠏'); else SPIN=('|' '/' '-' '\'); fi

SPIN_PID=""
cleanup() {
  if [ -n "$SPIN_PID" ]; then kill "$SPIN_PID" 2>/dev/null || true; fi
  if [ "$ANIM" = 1 ]; then printf '\e[?25h'; fi
  return 0
}
trap cleanup EXIT
trap 'cleanup; printf "\n"; exit 130' INT TERM

# spin "Label" command… → runs it (its output goes to $LOG) with a spinner, then ✔ or ✖. Returns its status.
spin() {
  local label="$1" rc=0 i=0 t0=$SECONDS el
  shift
  [ -n "$LOG" ] || LOG=$(mktemp /tmp/finesse-install.XXXXXX)
  printf '\n--- %s\n' "$label" >>"$LOG"
  # A password prompt under a spinner gets lost, so ask for it first.
  if [ -n "$SUDO" ] && ! sudo -n true 2>/dev/null; then sudo -v </dev/tty || true; fi
  if [ "$ANIM" = 1 ]; then
    "$@" >>"$LOG" 2>&1 </dev/null &
    SPIN_PID=$!
    printf '\e[?25l'
    while kill -0 "$SPIN_PID" 2>/dev/null; do
      el=$((SECONDS - t0)); if [ "$el" -ge 3 ]; then el=" ${el}s"; else el=""; fi
      printf '\r    %s%s%s %s%s%s%s\e[K' "$ACC" "${SPIN[i % ${#SPIN[@]}]}" "$N" "$label" "$D" "$el" "$N"
      i=$((i + 1)); sleep 0.1
    done
    wait "$SPIN_PID" || rc=$?
    SPIN_PID=""
    printf '\r\e[K\e[?25h'
  else
    say "    $label…"
    "$@" >>"$LOG" 2>&1 </dev/null || rc=$?
  fi
  if [ "$rc" = 0 ]; then [ "$ANIM" = 1 ] && ok "$label"; else printf '    %s%s%s %s\n' "$R" "$I_ERR" "$N" "$label"; fi
  return "$rc"
}
# The last lines of the log, for when something failed.
log_tail() { if [ -n "$LOG" ]; then tail -n "${1:-12}" "$LOG" | sed 's/^/      /' >&2; fi; return 0; }

# draw ART line… → Nessa in half blocks (two pixels a cell), a line of text beside each row.
draw() {
  local art="$1" r x t b ti bi seq prev line top bot p ch
  shift
  local -a rows side fg bg
  side=("$@")
  IFS=$'\n' read -r -d '' -a rows <<<"$art" || true
  for ((x = 0; x < ${#NESSA_TC[@]}; x++)); do
    if [ "$ART" = tc ]; then fg[x]="38;2;${NESSA_TC[x]}"; bg[x]="48;2;${NESSA_TC[x]}"
    else fg[x]="38;5;${NESSA_256[x]}"; bg[x]="48;5;${NESSA_256[x]}"; fi
  done
  for ((r = 0; r < ${#rows[@]}; r += 2)); do
    top=${rows[r]}; bot=${rows[r + 1]:-}; line=""; prev=""
    for ((x = 0; x < ${#top}; x++)); do
      t=${top:x:1}; b=${bot:x:1}; b=${b:-.}
      p=${NESSA_ALPHA%%"$t"*}; ti=${#p}
      p=${NESSA_ALPHA%%"$b"*}; bi=${#p}
      if [ "$t" = . ] && [ "$b" = . ]; then seq="0"; ch=" "
      elif [ "$b" = . ]; then seq="0;${fg[ti]}"; ch="▀"
      elif [ "$t" = . ]; then seq="0;${fg[bi]}"; ch="▄"
      elif [ "$t" = "$b" ]; then seq="0;${fg[ti]}"; ch="█"
      else seq="0;${fg[ti]};${bg[bi]}"; ch="▀"; fi
      if [ "$seq" != "$prev" ]; then line="$line"$'\e['"${seq}m"; prev=$seq; fi
      line="$line$ch"
    done
    printf '  %s\e[0m  %s\n' "$line" "${side[r / 2]:-}"
  done
}
art_width() { local -a rows; IFS=$'\n' read -r -d '' -a rows <<<"$1" || true; echo "${#rows[0]}"; }

# "Finesse." in Nessa's colours: hair blue to violet to pink.
WORDMARK=""
letters=(F i n e s s e)
if [ "$ART" = tc ]; then cols=("92;180;255" "113;168;254" "136;154;252" "160;141;250" "190;131;232" "218;122;206" "244;114;182"); pre="1;38;2;"
elif [ "$ART" = 256 ]; then cols=(75 111 147 141 177 213 212); pre="1;38;5;"
else cols=(); fi
if [ "${#cols[@]}" -gt 0 ]; then
  for i in 0 1 2 3 4 5 6; do WORDMARK="$WORDMARK"$'\e['"${pre}${cols[i]}m${letters[i]}"; done
  WORDMARK="$WORDMARK$N$HAIR$B.$N"
else
  WORDMARK="$B${ACC}Finesse$N$HAIR.$N"
fi

# Pictures only where the terminal can show them and the installer carries them (tools/installer/art.py).
has_art() { [ "$ART" != 0 ] && [ -n "${1:-}" ]; }

banner() {
  local w=0 tag="${D}your own streaming service${N}" e="$D$PINK"
  has_art "${NESSA_HI:-}" && w=$(art_width "$NESSA_HI")
  printf '\n'
  if has_art "${NESSA_HI:-}" && [ "$COLS" -ge $((w + 32)) ]; then
    draw "$NESSA_HI" "" "$WORDMARK" "$tag" "" "" \
      "${e}╭────────────────────────╮${N}" \
      "${e}│${N} Hi! I'm Nessa.         ${e}│${N}" \
      "${e}◀${N} Let's set up your own  ${e}│${N}" \
      "${e}│${N} streaming service.     ${e}│${N}" \
      "${e}╰────────────────────────╯${N}" \
      "" "" "" "" "${D}github.com/CoffeeCC/finesse${N}"
  else
    if has_art "${NESSA_HI:-}" && [ "$COLS" -ge $((w + 4)) ]; then draw "$NESSA_HI"; printf '\n'; fi
    printf '  %s  %s\n' "$WORDMARK" "$tag"
    nessa "Hi! I'm Nessa. Let's set up your own streaming service."
  fi
}

# finale "Headline" "Sentence" → Nessa cheering, the sentence wrapped beside her (or just the two lines).
finale() {
  local w=0 head="$1" text="$2"
  local -a lines
  has_art "${NESSA_YAY:-}" && w=$(art_width "$NESSA_YAY")
  printf '\n'
  if has_art "${NESSA_YAY:-}" && [ "$COLS" -ge $((w + 26)) ]; then
    IFS=$'\n' read -r -d '' -a lines < <(printf '%s\n' "$text" | fold -s -w 22) || true
    draw "$NESSA_YAY" "" "" "" "" "" "" "$G$B$head$N" "" "${lines[@]}"
  else
    printf '  %s%s%s %s\n' "$G$B" "$head" "$N" "$text"
  fi
}

# The address between two rules: easy to spot, nothing else on its line to copy by mistake.
show_url() {
  local u="$1" rule="" n=$(( ${#1} + 6 ))
  while [ "$n" -gt 0 ]; do rule="$rule$RULE"; n=$((n - 1)); done
  printf '\n  %s%s%s\n     %s%s%s\n  %s%s%s\n' "$ACC$D" "$rule" "$N" "$B" "$u" "$N" "$ACC$D" "$rule" "$N"
}

