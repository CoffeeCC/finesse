# /etc/os-release is read in a subshell: it sets VERSION, which is ours.
osr() { ( . /etc/os-release 2>/dev/null; eval "printf '%s' \"\${$1:-}\"" ) || true; }
OS_ID=$(osr ID); OS_LIKE=$(osr ID_LIKE); OS_NAME=$(osr PRETTY_NAME); OS_NAME=${OS_NAME:-Linux}; OS_SHORT=$(osr NAME); OS_SHORT=${OS_SHORT:-$OS_NAME}
