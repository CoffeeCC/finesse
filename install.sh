# ---------- Nessa (generated by tools/installer/art.py from the PNGs beside it; do not edit by hand) ----------
# ---------- /Nessa ----------

say()  { printf '%s\n' "$*"; }
ok()   { printf '    %s%s%s %s\n' "$G" "$I_OK" "$N" "$*"; }
warn() { printf '    %s!%s %s\n' "$Y" "$N" "$*"; }
nessa() { printf '    %sNessa ›%s %s\n' "$PINK" "$N" "$*"; }
die() {
  printf '\n    %s%s %s%s\n' "$R" "$I_ERR" "$*" "$N" >&2
  if [ -n "$LOG" ] && [ -s "$LOG" ]; then printf '    %sEverything it printed: %s%s\n' "$D" "$LOG" "$N" >&2; fi
  printf '    %sHelp: %s%s\n' "$D" "$DOCS" "$N" >&2
  nessa "Fix that and run me again. I'll pick up where we left off." >&2
  printf '\n' >&2
  exit 1
}
STEP_N=0
step() {
  STEP_N=$((STEP_N + 1))
  local title="$STEP_N · $*" rule="" n
  n=$(( 56 - ${#title} )); [ "$n" -lt 4 ] && n=4
  while [ "$n" -gt 0 ]; do rule="$rule$RULE"; n=$((n - 1)); done
  printf '\n  %s%s%s%s %s%s%s %s%s%s\n' "$ACC" "$RULE" "$RULE" "$N" "$B" "$title" "$N" "$ACC$D" "$rule" "$N"
}

# Prompts read from the terminal even when this script is piped into bash.
ask() { # ask "Question" default [hint] → echoes the answer (the hint replaces "[default]")
  local q="$1" def="${2:-}" hint="${3:-[$2]}" ans=""
  if [ "$YES" = 1 ] || [ ! -r /dev/tty ]; then echo "$def"; return; fi
  printf '    %s?%s %s%s%s %s%s%s ' "$ACC" "$N" "$B" "$q" "$N" "$D" "$hint" "$N" >/dev/tty
  read -r ans </dev/tty || true
  echo "${ans:-$def}"
}
confirm() { # confirm "Question" (default yes)
  local a
  a=$(ask "$1" "y" "(Y/n)")
  case "$a" in [nN]*) return 1 ;; *) return 0 ;; esac
}

usage() {
  if [ -r "$0" ] && head -1 "$0" | grep -q bash; then sed -n '2,/^[^#]/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'
  else say "See $DOCS"; fi
  exit 0
}

while [ $# -gt 0 ]; do
  case "$1" in
    --data) DATA="$2"; shift 2 ;;
    --root) ROOT="$2"; ROOT_SET=1; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --version) VERSION="${2#v}"; shift 2 ;;
    --image) IMAGE="$2"; shift 2 ;;
    --setup) SETUP_FILE="$2"; shift 2 ;;
    --yes|-y) YES=1; shift ;;
    --plain) PLAIN=1; shift ;;
    --uninstall) UNINSTALL=1; shift ;;
    --help|-h) usage ;;
    *) die "Unknown option: $1 (see --help)" ;;
  esac
done
