if [ -z "$DOCKER_BIN" ]; then
  install_docker
  DOCKER_BIN=$(command -v docker 2>/dev/null || echo /usr/bin/docker)
fi
if ! docker_ info >/dev/null 2>&1; then
  if ! spin "Starting Docker" start_docker; then
    log_tail 6
    if [ "$LXC" = 1 ]; then die "Docker can't start inside this container. In Proxmox, turn on Nesting (and keyctl) under the container's Options → Features, restart it, and run this again."
    elif [ "$WSL" = 1 ] && [ ! -d /run/systemd/system ]; then die "Docker can't start because WSL isn't running systemd. Add [boot] systemd=true to /etc/wsl.conf, run wsl --shutdown in Windows, and run this again (or use Docker Desktop's WSL integration)."
    else die "Docker is installed but won't start. Look at: sudo journalctl -u docker -n 30"; fi
  fi
fi
ok "Docker $(docker_ version --format '{{.Server.Version}}' 2>/dev/null || true)"
# Fedora, Bazzite, RHEL…: SELinux keeps containers out of their folders unless told otherwise.
SECOPT=""
if docker_ info --format '{{json .SecurityOptions}}' 2>/dev/null | grep -q selinux; then
  SECOPT="--security-opt label=disable"
  ok "SELinux is on; Finesse's apps will be allowed into their folders"
fi

# ---------- already installed? ----------
existing=$(docker_ ps -a --filter "name=^/${NAME}$" --format '{{.Status}}' || true)
if [ -n "$existing" ]; then
  step "Finesse is already installed"
  case "$existing" in Up*) ok "Running ($existing)" ;; *) docker_ start "$NAME" >/dev/null && ok "Started it again" ;; esac
  PORT=$(docker_ port "$NAME" 8080/tcp 2>/dev/null | head -1 | sed 's/.*://' || echo "$PORT")
  PORT=${PORT:-8080}
  say "    ${D}Updates happen from inside Finesse (Settings → Updates). To start over, run the installer with --uninstall.${N}"
else
  # ---------- folders ----------
  step "Where things go"
  if [ "$NAS" = truenas ] && [ "$ROOT_SET" = 0 ]; then
    pool=$(ls -d /mnt/*/ 2>/dev/null | grep -v -e '/mnt/\.' -e 'ix-apps' | head -1 || true)
    [ -n "$pool" ] || die "No pool found under /mnt. Create one in TrueNAS (Storage), then run this again."
    ROOT=$(ask "Settings folder (on a pool)" "${pool%/}/finesse")
  fi
  if [ -z "$DATA" ]; then
    say "    Movies, shows, music and downloads need space. Disks with the most room:"
    df -P -k -x tmpfs -x devtmpfs -x overlay -x squashfs -x efivarfs 2>/dev/null | awk 'NR>1 { printf "%d GB free  %s\n", $4*1024/1e9, $6 }' | sort -rn | head -4 | sed "s|^|      $D|; s|\$|$N|" || true
    DATA=$(ask "Media & downloads folder" "${DATA_DEFAULT:-$ROOT/data}")
  fi
  ROOT="${ROOT%/}"; DATA="${DATA%/}"
  case "$ROOT$DATA" in *" "*) die "Please use folder paths without spaces." ;; esac
  case "$NAS" in
    truenas|unraid)
      for d in "$ROOT" "$DATA"; do
        case "$d" in /mnt/?*) ;; *) die "On a NAS, keep Finesse's folders on a pool (under /mnt/), not $d: system updates replace everything else." ;; esac
      done ;;
    synology)
      for d in "$ROOT" "$DATA"; do
        case "$d" in /volume[0-9]*/?*) ;; *) die "On Synology, keep Finesse's folders on a volume (under /volume1/ or similar), not $d." ;; esac
      done ;;
  esac
  $SUDO mkdir -p "$ROOT/config" "$DATA" || die "Couldn't create $ROOT or $DATA"
  free_gb=$(df -P -k "$DATA" | awk 'NR==2 { printf "%d", $4*1024/1e9 }')
  ok "Settings in $ROOT"
  ok "Media in $DATA (${free_gb} GB free)"
  [ "${free_gb:-0}" -lt 50 ] && warn "That's not much room. A single 4K movie can be 50 GB."

  # The apps run as this user so your files stay yours.
  if [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != root ]; then
    PUID=$(id -u "$SUDO_USER"); PGID=$(id -g "$SUDO_USER")
  elif [ "$(id -u)" != 0 ]; then
    PUID=$(id -u); PGID=$(id -g)
  elif [ "$NAS" = truenas ]; then
    PUID=568; PGID=568   # TrueNAS's "apps" user, like its own apps
  elif [ "$NAS" = unraid ]; then
    PUID=99; PGID=100    # Unraid's nobody:users, like its own apps
  else
    PUID=1000; PGID=1000
  fi
  $SUDO chown "$PUID:$PGID" "$ROOT/config" "$DATA" 2>/dev/null || true

  TZ_NAME=$(timedatectl show -p Timezone --value 2>/dev/null || cat /etc/timezone 2>/dev/null || readlink /etc/localtime 2>/dev/null | sed 's|.*/zoneinfo/||' || true)
  TZ_NAME=${TZ_NAME:-UTC}

  # ---------- port ----------
  port_busy() { (command -v ss >/dev/null 2>&1 && ss -ltn "( sport = :$1 )" | grep -q ":$1 ") || (echo >/dev/tcp/127.0.0.1/"$1") 2>/dev/null; }
  want=$PORT
  while port_busy "$PORT"; do PORT=$((PORT + 1)); [ "$PORT" -gt $((want + 20)) ] && die "Ports $want–$PORT are all in use. Pick one with --port."; done
  [ "$PORT" != "$want" ] && warn "Port $want is in use, so Finesse will use $PORT."

  # ---------- start ----------
  step "Starting Finesse"
  if ! spin "Downloading Finesse" docker_ pull "$IMAGE"; then
    [ -n "$(docker_ images -q "$IMAGE")" ] || { log_tail 4; die "Couldn't download $IMAGE. Check the internet connection (and the version, if you gave one)."; }
    warn "Using the copy already on this machine"
  fi
  docker_ network inspect "$NETWORK" >/dev/null 2>&1 || docker_ network create "$NETWORK" --label finesse.managed=true >/dev/null
  # SECOPT is two words or none, so it's left unquoted.
  docker_ run -d --name "$NAME" \
    --restart unless-stopped \
    --network "$NETWORK" --network-alias finesse \
    -p "$PORT:8080" $SECOPT \
    -v /var/run/docker.sock:/var/run/docker.sock \
    -v "$ROOT:$ROOT" -v "$DATA:$DATA" \
    -e FINESSE_ROOT="$ROOT" -e FINESSE_DATA="$DATA" -e FINESSE_CONFIG_DIR="$ROOT/config/finesse" \
    -e PUID="$PUID" -e PGID="$PGID" -e TZ="$TZ_NAME" \
    "$IMAGE" >/dev/null || die "Docker couldn't start Finesse."
  ok "Started on port $PORT"
fi

# ---------- wait until it answers ----------
health() {
  if command -v curl >/dev/null 2>&1; then curl -fsS "http://127.0.0.1:$PORT/api/health" >/dev/null 2>&1
  else wget -q -O /dev/null "http://127.0.0.1:$PORT/api/health" 2>/dev/null; fi
}
wait_health() { for _ in $(seq 1 90); do health && return 0; sleep 1; done; return 1; }
health || spin "Waiting for Finesse to wake up" wait_health || die "Finesse didn't answer on port $PORT. See: sudo docker logs $NAME"

# Firewalls that turn other devices away by default (Fedora Server, RHEL…): let the web app through.
if command -v firewall-cmd >/dev/null 2>&1 && systemctl is-active --quiet firewalld 2>/dev/null; then
  if ! $SUDO firewall-cmd --query-port="$PORT/tcp" >/dev/null 2>&1; then
    if $SUDO firewall-cmd --permanent --add-port="$PORT/tcp" >/dev/null 2>&1 && $SUDO firewall-cmd --reload >/dev/null 2>&1; then ok "Let port $PORT through the firewall"
    else warn "Couldn't open port $PORT in the firewall. Run: sudo firewall-cmd --permanent --add-port=$PORT/tcp && sudo firewall-cmd --reload"; fi
  fi
fi

# The address people at home reach this machine on: the one the default route
# leaves from, unless that's a VPN; else the first real network card's.
# (`hostname -I` lists Docker bridges and Tailscale too, in no useful order.)
virtual_if='^(docker|br-|veth|virbr|cni|flannel|cali|tailscale|tun|tap|wg|zt|lo)'
IP=""
route_dev=$(ip route get 1.1.1.1 2>/dev/null | awk '{for (i=1;i<NF;i++) if ($i=="dev") print $(i+1)}' || true)
if [ -n "$route_dev" ] && ! printf '%s' "$route_dev" | grep -Eq "$virtual_if"; then
  IP=$(ip route get 1.1.1.1 2>/dev/null | awk '{for (i=1;i<NF;i++) if ($i=="src") print $(i+1)}' || true)
fi
[ -n "$IP" ] || IP=$(ip -4 -o addr show scope global 2>/dev/null | awk '{print $2, $4}' | grep -Ev "$virtual_if" | head -1 | awk '{sub("/.*","",$2); print $2}' || true)
[ -n "$IP" ] || IP=$(hostname -I 2>/dev/null | awk '{print $1}' || true)
IP=${IP:-localhost}
URL="http://$IP:$PORT"

# ---------- headless setup ----------
if [ -n "$SETUP_FILE" ]; then
  [ -r "$SETUP_FILE" ] || die "Can't read $SETUP_FILE"
  step "Applying $SETUP_FILE"
  docker_ exec -i "$NAME" finesse setup apply - <"$SETUP_FILE" || die "Setup stopped. Fix the problem above and run: sudo docker exec -i $NAME finesse setup apply - < $SETUP_FILE"
  finale "Your server is ready." "Open it on any phone, TV or computer at home and sign in."
  show_url "$URL"
  say ""
  exit 0
fi

CODE=$(docker_ exec "$NAME" finesse setup-code 2>/dev/null || true)
if [ -n "$CODE" ]; then
  finale "All set!" "Finesse is running. Open the link below on any phone or computer at home to finish setting up."
  show_url "$URL/finesse/setup?code=$CODE"
  say "    Setup code ${B}$CODE${N}   ${D}show it again: sudo docker exec $NAME finesse setup-code${N}"
  if command -v qrencode >/dev/null 2>&1; then say ""; qrencode -t ANSIUTF8 -m 2 "$URL/finesse/setup?code=$CODE" | sed 's/^/  /'; fi
else
  finale "Finesse is running." "Open it on any phone, TV or computer at home."
  show_url "$URL"
fi
say ""
say "    ${D}Health check any time: sudo docker exec $NAME finesse doctor${N}"
say "    ${D}Finesse is free. Tips welcome (ETH): $TIP${N}"
say ""
if [ -n "$LOG" ]; then rm -f "$LOG"; fi
exit 0
